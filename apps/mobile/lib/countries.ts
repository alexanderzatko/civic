function localeKey(locale: string): "en" | "sk" {
  return locale.toLowerCase().startsWith("sk") ? "sk" : "en";
}

export function countryLabel(iso2: string, locale: string): string {
  const code = iso2.toUpperCase();
  const mapped = COUNTRY_NAMES[localeKey(locale)][code];
  if (mapped) return mapped;
  try {
    return (
      new Intl.DisplayNames([locale], { type: "region" }).of(code) ?? code
    );
  } catch {
    return code;
  }
}

/** Localised country options, sorted by label; `preferred` codes stay on top. */
export function listCountries(
  locale: string,
  preferred: string[] = ["SK"],
): CountryOption[] {
  const options: CountryOption[] = COUNTRY_ISO2.map((iso2) => ({
    iso2,
    label: countryLabel(iso2, locale),
  }));
  const pref = new Set(preferred.map((c) => c.toUpperCase()));
  const top: CountryOption[] = [];
  for (const code of preferred) {
    const match = options.find((o) => o.iso2 === code.toUpperCase());
    if (match) top.push(match);
  }
  const rest = options
    .filter((o) => !pref.has(o.iso2))
    .sort((a, b) => a.label.localeCompare(b.label, locale));
  return [...top, ...rest];
}

export function isCountryIso2(value: string): boolean {
  return (COUNTRY_ISO2 as readonly string[]).includes(value.toUpperCase());
}
